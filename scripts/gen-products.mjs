// Generates app/landing/products.ts from video/src/products.json (the demo film's data, same products as the page).
// Usage: npm run gen:products [-- path/to/products.json]
// The Arabic below is the approved copy from the landing mock's AR dictionary (combo.html T_AR, product data block).
// Product names, units and store marks stay as data; a string with no Arabic here fails the run.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = resolve(root, process.argv[2] ?? "video/src/products.json");
const out = resolve(root, "app/landing/products.ts");

const AR = {
  "Phone charger": "شاحن موبايل", iPhone: "آيفون", Skincare: "عناية بالبشرة", "Air fryer": "قلاية هوائية", Diapers: "حفاضات",
  "= same model": "= نفس الموديل", "= same storage": "= نفس المساحة", "= same color": "= نفس اللون", "= same wattage": "= نفس الوات",
  "= same formula": "= نفس التركيبة", "= same 454g size": "= نفس الحجم 454g", "= same series": "= نفس الفئة", "= same 4.1L size": "= نفس الحجم 4.1L",
  "= same line": "= نفس النوع", "= same size 4": "= نفس المقاس 4", "= same 64 count": "= نفس العدد 64",
  "≠ different variant": "≠ نسخة مختلفة", "≠ different model": "≠ موديل مختلف", "≠ different size": "≠ حجم مختلف", "≠ smaller pack": "≠ عبوة أصغر",
  "20W, not 30W": "20W مش 30W", "White, not Black": "أبيض مش أسود", "Different model": "موديل تاني", "Pro, not Pro Max": "Pro مش Pro Max",
  "512GB, not 256GB": "512GB مش 256GB", "Deep Blue, not Orange": "أزرق غامق مش برتقاني", "340g, not 454g": "340g مش 454g",
  "Lotion, not cream": "لوشن مش كريم", "Pack of 2": "عبوة من 2", "2000 Series, not 3000": "2000 Series مش 3000", "6.2L, not 4.1L": "6.2L مش 4.1L",
  "44, not 64 diapers": "44 حفاضة مش 64", "Premium Care, not Baby-Dry": "Premium Care مش Baby-Dry", "Size 5, not 4": "مقاس 5 مش 4",
  "model, wattage and color": "الموديل والوات واللون", "model, storage and color": "الموديل والمساحة واللون", "formula, size and pack": "التركيبة والحجم والعبوة",
  "series, size and color": "الفئة والحجم واللون", "line, size and count": "النوع والمقاس والعدد",
  "■ Store · 44 count": "■ Store · 44 حفاضة",
};
const ar = (s) => {
  if (!(s in AR)) throw new Error(`gen-products: no Arabic for "${s}"`);
  return AR[s];
};
// Store labels other than the one translated above keep their English detail (a model or size), as in the mock.
const arLabel = (s) => AR[s] ?? s;

// the English tags are written "= same model"; the page shows them sentence-cased ("= Same model")
const cap = (s) => s.replace(/^= (\w)/, (_, c) => "= " + c.toUpperCase());
const data = JSON.parse(readFileSync(src, "utf8")).map((p) => ({
  ...p,
  tags: p.tags.map(cap),
  ar: {
    chip: ar(p.chip),
    checks: ar(p.checks),
    tags: p.tags.map(ar),
    lookalike: { label: arLabel(p.lookalike.label), reason: ar(p.lookalike.reason) },
    why: p.lineup.map((l) => (l[5] ? ar(l[5]) : null)),
  },
}));

const ts = `// Generated by scripts/gen-products.mjs from video/src/products.json. Do not edit by hand.
import type { Locale } from "../../lib/i18n";

/** "● Store" (A, circle), "▲ Store" (B, triangle), "■ Store" (C, square), optionally followed by " · detail". */
export type StoreLabel = string;
/** [store, listing name, price EGP, art classes, 1 = the exact product, why it is not (look-alikes only)] */
export type LineupRow = [StoreLabel, string, number, string, 0 | 1, string?];

export interface Product {
  id: string;
  chip: string;
  name: string;
  short: string;
  title: string;
  brand: string;
  rating: string;
  ratings: string;
  slug: string;
  tab: string;
  bullet: string;
  checks: string;
  tags: string[];
  art: string;
  from: number;
  on: StoreLabel;
  best: { store: StoreLabel; price: number };
  other: { store: StoreLabel; price: number };
  lookalike: { label: StoreLabel; reason: string; price: number };
  alert: number;
  weeks: number[];
  units: string[];
  lineup: LineupRow[];
  /** Arabic for the demo strings (approved mock copy). why[i] belongs to lineup[i]. */
  ar: { chip: string; checks: string; tags: string[]; lookalike: { label: StoreLabel; reason: string }; why: (string | null)[] };
}

export const products: Product[] = ${JSON.stringify(data, null, 2)};

/** The product for \`?p=\`; anything unknown (or nothing) is the first one. */
export function getProduct(id?: string | null): Product {
  return products.find((p) => p.id === id) ?? products[0];
}

/** The product with its demo strings in the page language. */
export function localize(p: Product, locale: Locale): Product {
  if (locale !== "ar") return p;
  return {
    ...p,
    chip: p.ar.chip,
    checks: p.ar.checks,
    tags: p.ar.tags,
    lookalike: { ...p.lookalike, ...p.ar.lookalike },
    lineup: p.lineup.map((l, i) => (p.ar.why[i] ? [l[0], l[1], l[2], l[3], l[4], p.ar.why[i]!] : l)),
  };
}
`;
writeFileSync(out, ts);
console.log(`gen-products: ${data.length} products -> ${out}`);
