// One-way sync: gitprice monorepo -> this repo. Usage: node scripts/sync-design.mjs <monorepoPath>
// Never hand-edit the outputs (styles/tokens.css, i18n/*.json).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];
if (!root) {
  console.error("usage: node scripts/sync-design.mjs <monorepoPath>");
  process.exit(1);
}
const sha = execFileSync("git", ["-C", root, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
const ds = join(root, "design-system");

mkdirSync("styles", { recursive: true });
mkdirSync("i18n", { recursive: true });

// Drop the legacy Sora/Karla @font-face blocks: their relative urls do not exist here and the fonts are retired.
const css = readFileSync(join(ds, "colors_and_type.css"), "utf8").replace(
  /@font-face\s*\{[^}]*font-family:\s*'(?:Sora|Karla)'[^}]*\}\s*/g,
  "",
);
writeFileSync("styles/tokens.css", `/* GENERATED by scripts/sync-design.mjs from gitprice@${sha}. Do not edit. */\n${css}`);

for (const l of ["en", "ar"]) {
  const { web } = JSON.parse(readFileSync(join(ds, "i18n", `${l}.json`), "utf8"));
  if (!web) throw new Error(`${l}.json has no "web" key`);
  writeFileSync(`i18n/${l}.json`, JSON.stringify({ _source: `gitprice@${sha}`, web }, null, 2) + "\n");
}
console.log(`synced from gitprice@${sha}`);
